def canonical(value: str) -> str:
    """归一到本表 canonical 写法（无匹配时原样返回）。"""
    v = (value or "").strip()
    v = v.replace("（ ", "（").replace(" ）", "）")
    return ALIASES.get(v, v)


def scene_minor_options(major: str) -> list[str]:
    return [name for name, _ in SCENE_MINOR.get(major, [])]


def subject_minor_options(major: str) -> list[str]:
    return [name for name, _ in SUBJECT_MINOR.get(major, [])]


def movement_names() -> list[str]:
    return [name for name, _ in MOVEMENTS]


def movement_description(name: str) -> str:
    for n, d in MOVEMENTS:
        if n == name:
            return d
    return ""


def peiti_names() -> list[str]:
    """全部培体名（场景组在前，去重）。"""
    seen: list[str] = []
    for n, _ in PEITI_SCENE + PEITI_PERSON:
        if n not in seen:
            seen.append(n)
    return seen


def peiti_group(name: str) -> str:
    """返回培体所属组；两组同名（独立/其它）返回「场景培体_人物培体」。"""
    in_scene = any(n == name for n, _ in PEITI_SCENE)
    in_person = any(n == name for n, _ in PEITI_PERSON)
    if in_scene and in_person:
        return "场景培体_人物培体"
    if in_scene:
        return "场景培体"
    if in_person:
        return "人物培体"
    return ""
